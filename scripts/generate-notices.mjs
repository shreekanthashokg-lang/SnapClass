/**
 * Writes public/third-party-notices.txt: the name, version, licence and full licence
 * text of every package that ships in the production bundle (the `dependencies`
 * tree, including fonts). Re-run after changing dependencies:  npm run notices
 */
import { existsSync } from "node:fs";
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const modules = path.join(root, "node_modules");
const rootPkg = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));

const seen = new Map();

async function visit(name, from) {
  // Resolve like Node does: nested node_modules first, then hoisted.
  const candidates = [path.join(from, "node_modules", name), path.join(modules, name)];
  const dir = candidates.find((candidate) => existsSync(path.join(candidate, "package.json")));
  if (!dir) return; // optional or platform-specific dependency that is not installed
  const pkg = JSON.parse(await readFile(path.join(dir, "package.json"), "utf8"));
  const key = `${pkg.name}@${pkg.version}`;
  if (seen.has(key)) return;
  const files = await readdir(dir);
  const licenceFile = files.find((file) => /^(licen[cs]e|copying)(\..*)?$/i.test(file));
  const text = licenceFile ? (await readFile(path.join(dir, licenceFile), "utf8")).trim() : "(no licence file shipped in the package)";
  const licence = typeof pkg.license === "string" ? pkg.license : (pkg.license?.type ?? "see licence text");
  seen.set(key, { name: pkg.name, version: pkg.version, licence, homepage: pkg.homepage ?? pkg.repository?.url ?? "", text });
  for (const dep of Object.keys(pkg.dependencies ?? {})) await visit(dep, dir);
}

for (const dep of Object.keys(rootPkg.dependencies ?? {})) await visit(dep, root);

const entries = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
const header = `SnapClass website: open-source software notices

This site is designed and built by Shreekanth A Guttedar. It includes the open-source
packages listed below, each provided under its own licence. They remain the work of their
respective authors. This file is generated by scripts/generate-notices.mjs.

Packages: ${entries.length}
`;
const body = entries
  .map((e) => `\n${"=".repeat(72)}\n${e.name} ${e.version}\nLicence: ${e.licence}${e.homepage ? `\nSource: ${e.homepage}` : ""}\n${"-".repeat(72)}\n${e.text}\n`)
  .join("");
await writeFile(path.join(root, "public", "third-party-notices.txt"), header + body);
console.log(`[notices] ${entries.length} packages -> public/third-party-notices.txt`);
for (const e of entries) console.log(`  ${e.name}@${e.version}  ${e.licence}`);
